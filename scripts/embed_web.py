# PlatformIO pre-build script: embeds the web UI (web/) into the firmware.
#
# Every file in web/ is lightly minified, gzipped and written as a byte array into the
# generated header src/web_assets.h together with its MIME type and an ETag. The firmware
# serves these with "Content-Encoding: gzip", so the UI ships with a normal OTA upload and
# never needs `uploadfs` (which would wipe wifi.txt, mqtt.txt and schedules.json).
#
# Uses only the Python standard library (PlatformIO's bundled Python), no Node.

import gzip
import hashlib
import os
import re

Import("env")  # noqa: F821 (provided by SCons)

PROJECT_DIR = env["PROJECT_DIR"]  # noqa: F821
WEB_DIR = os.path.join(PROJECT_DIR, "web")
OUT_FILE = os.path.join(PROJECT_DIR, "src", "web_assets.h")
MAX_TOTAL_GZ = 40 * 1024

MIME_TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".json": "application/json",
    ".svg": "image/svg+xml",
    ".ico": "image/x-icon",
    ".png": "image/png",
}


def minify(text, ext):
    # Conservative: only comments and indentation, gzip does the rest. For JS only whole-line
    # // comments are dropped; stripping /* */ could hit "/*" inside strings or line comments.
    if ext == ".css":
        text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    if ext == ".html":
        text = re.sub(r"<!--.*?-->", "", text, flags=re.S)
    lines = []
    for line in text.splitlines():
        line = line.strip()
        if not line or (ext == ".js" and line.startswith("//")):
            continue
        lines.append(line)
    return "\n".join(lines) + "\n"


def c_identifier(name):
    return "web_" + re.sub(r"[^A-Za-z0-9]", "_", name)


def build():
    if not os.path.isdir(WEB_DIR):
        print("embed_web: no web/ directory, skipping")
        return

    assets = []
    for root, _, files in os.walk(WEB_DIR):
        for name in sorted(files):
            full = os.path.join(root, name)
            rel = os.path.relpath(full, WEB_DIR).replace(os.sep, "/")
            ext = os.path.splitext(name)[1].lower()
            if ext not in MIME_TYPES:
                print("embed_web: skipping %s (unknown type)" % rel)
                continue
            with open(full, "rb") as f:
                data = f.read()
            if ext in (".html", ".js", ".css", ".svg"):
                data = minify(data.decode("utf-8"), ext).encode("utf-8")
            gz = gzip.compress(data, compresslevel=9, mtime=0)
            etag = '"%s"' % hashlib.sha1(gz).hexdigest()[:16]
            assets.append((rel, MIME_TYPES[ext], gz, etag))
    assets.sort()

    out = [
        "// Generated by scripts/embed_web.py from web/ -- do not edit.",
        "#pragma once",
        "#include <Arduino.h>",
        "",
        "struct WebAsset",
        "{",
        "  const char *path;",
        "  const char *mime;",
        "  const uint8_t *data;",
        "  size_t length;",
        "  const char *etag;",
        "};",
        "",
    ]
    for rel, _, gz, _ in assets:
        out.append("static const uint8_t %s[] PROGMEM = {" % c_identifier(rel))
        for i in range(0, len(gz), 24):
            out.append("  " + ",".join(str(b) for b in gz[i:i + 24]) + ",")
        out.append("};")
        out.append("")
    out.append("static const WebAsset webAssets[] = {")
    for rel, mime, gz, etag in assets:
        out.append('  {"/%s", "%s", %s, %d, "%s"},' % (rel, mime, c_identifier(rel), len(gz), etag.replace('"', '\\"')))
    out.append("};")
    out.append("static const size_t webAssetCount = %d;" % len(assets))
    out.append("")
    content = "\n".join(out)

    total = sum(len(a[2]) for a in assets)
    for rel, _, gz, _ in assets:
        print("embed_web: %-20s %6d bytes gzipped" % (rel, len(gz)))
    print("embed_web: total %d bytes gzipped (limit %d)" % (total, MAX_TOTAL_GZ))
    if total > MAX_TOTAL_GZ:
        print("embed_web: ERROR web bundle exceeds the size limit")
        env.Exit(1)  # noqa: F821

    # Only touch the header when it changes, so unchanged UI doesn't force a recompile
    old = None
    if os.path.exists(OUT_FILE):
        with open(OUT_FILE, "r", encoding="utf-8") as f:
            old = f.read()
    if old != content:
        with open(OUT_FILE, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)


build()
